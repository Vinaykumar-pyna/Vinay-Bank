import { zodResolver } from '@hookform/resolvers/zod';
import { Alert, Button, Col, Form, Modal, Row, Spinner } from 'react-bootstrap';
import { useForm, useWatch } from 'react-hook-form';
import toast from 'react-hot-toast';
import { z } from 'zod';
import { useGetBranchesQuery } from '@/features/banking/bankingApi';
import { PasswordStrengthMeter } from '@/features/auth/PasswordStrengthMeter';
import { ROLE_LABELS } from '@/features/auth/types';
import { errorMessage, fieldErrors, toApiError } from '@/lib/apiError';
import { MOBILE_REGEX, NAME_REGEX, passwordSchema } from '@/lib/validation';
import { useCreateStaffUserMutation } from '../staffApi';

const schema = z.object({
  firstName: z
    .string()
    .trim()
    .min(2, 'Enter the first name')
    .max(40)
    .regex(NAME_REGEX, 'Letters only'),
  lastName: z
    .string()
    .trim()
    .min(1, 'Enter the last name')
    .max(40)
    .regex(NAME_REGEX, 'Letters only'),
  email: z.string().trim().min(1, 'Enter the work email').email('Enter a valid email address'),
  phone: z.string().regex(MOBILE_REGEX, 'Enter a 10-digit Indian mobile number'),
  role: z.enum(['TELLER', 'MANAGER', 'ADMIN']),
  branchCode: z.string().regex(/^\d{4}$/, 'Choose a branch'),
  password: passwordSchema,
});

type StaffForm = z.infer<typeof schema>;

/** Admin creates a staff login. The employee ID is generated by the server. */
export function AddStaffModal({ onClose }: { onClose: () => void }) {
  const { data: branches = [] } = useGetBranchesQuery();
  const [create, { isLoading, error }] = useCreateStaffUserMutation();
  const {
    register,
    handleSubmit,
    control,
    formState: { errors },
  } = useForm<StaffForm>({
    resolver: zodResolver(schema),
    defaultValues: {
      firstName: '',
      lastName: '',
      email: '',
      phone: '',
      role: 'TELLER',
      branchCode: '0001',
      password: '',
    },
  });
  const password = useWatch({ control, name: 'password' });
  const serverErrors = fieldErrors(error ? toApiError(error) : undefined);

  const onSubmit = async (values: StaffForm) => {
    try {
      const user = await create(values).unwrap();
      toast.success(
        `${user.fullName} can now sign in as ${ROLE_LABELS[user.role].toLowerCase()} (${user.employeeId})`,
      );
      onClose();
    } catch {
      // Shown in the form.
    }
  };

  const fieldError = (name: keyof StaffForm) => errors[name]?.message ?? serverErrors[name];

  return (
    <Modal show onHide={onClose} centered size="lg">
      <Form noValidate onSubmit={handleSubmit(onSubmit)}>
        <Modal.Header closeButton>
          <Modal.Title as="h2" className="h5">
            Add staff member
          </Modal.Title>
        </Modal.Header>
        <Modal.Body>
          {error && !Object.keys(serverErrors).length && (
            <Alert variant="danger">{errorMessage(error)}</Alert>
          )}
          <Row className="g-3">
            <Col md={6}>
              <Form.Group controlId="staff-first-name">
                <Form.Label>First name</Form.Label>
                <Form.Control
                  {...register('firstName')}
                  isInvalid={!!fieldError('firstName')}
                  autoComplete="off"
                />
                <Form.Control.Feedback type="invalid">
                  {fieldError('firstName')}
                </Form.Control.Feedback>
              </Form.Group>
            </Col>
            <Col md={6}>
              <Form.Group controlId="staff-last-name">
                <Form.Label>Last name</Form.Label>
                <Form.Control
                  {...register('lastName')}
                  isInvalid={!!fieldError('lastName')}
                  autoComplete="off"
                />
                <Form.Control.Feedback type="invalid">
                  {fieldError('lastName')}
                </Form.Control.Feedback>
              </Form.Group>
            </Col>
            <Col md={6}>
              <Form.Group controlId="staff-email">
                <Form.Label>Work email</Form.Label>
                <Form.Control
                  type="email"
                  {...register('email')}
                  isInvalid={!!fieldError('email')}
                  autoComplete="off"
                />
                <Form.Control.Feedback type="invalid">{fieldError('email')}</Form.Control.Feedback>
              </Form.Group>
            </Col>
            <Col md={6}>
              <Form.Group controlId="staff-phone">
                <Form.Label>Mobile</Form.Label>
                <Form.Control
                  inputMode="numeric"
                  maxLength={10}
                  {...register('phone')}
                  isInvalid={!!fieldError('phone')}
                />
                <Form.Control.Feedback type="invalid">{fieldError('phone')}</Form.Control.Feedback>
              </Form.Group>
            </Col>
            <Col md={6}>
              <Form.Group controlId="staff-role">
                <Form.Label>Role</Form.Label>
                <Form.Select {...register('role')}>
                  <option value="TELLER">Teller (maker)</option>
                  <option value="MANAGER">Branch manager (checker)</option>
                  <option value="ADMIN">Administrator</option>
                </Form.Select>
              </Form.Group>
            </Col>
            <Col md={6}>
              <Form.Group controlId="staff-branch">
                <Form.Label>Branch</Form.Label>
                <Form.Select {...register('branchCode')} isInvalid={!!fieldError('branchCode')}>
                  {branches.map((b) => (
                    <option key={b.code} value={b.code}>
                      {b.name} ({b.code})
                    </option>
                  ))}
                </Form.Select>
                <Form.Control.Feedback type="invalid">
                  {fieldError('branchCode')}
                </Form.Control.Feedback>
              </Form.Group>
            </Col>
            <Col md={12}>
              <Form.Group controlId="staff-password">
                <Form.Label>Temporary password</Form.Label>
                <Form.Control
                  type="password"
                  autoComplete="new-password"
                  {...register('password')}
                  isInvalid={!!fieldError('password')}
                />
                <Form.Control.Feedback type="invalid">
                  {fieldError('password')}
                </Form.Control.Feedback>
                <PasswordStrengthMeter password={password} />
                <Form.Text>
                  Share it through a secure channel and ask them to change it after the first
                  sign-in.
                </Form.Text>
              </Form.Group>
            </Col>
          </Row>
        </Modal.Body>
        <Modal.Footer>
          <Button variant="outline-secondary" onClick={onClose} disabled={isLoading}>
            Cancel
          </Button>
          <Button type="submit" disabled={isLoading}>
            {isLoading && <Spinner size="sm" className="me-2" />}
            Create staff login
          </Button>
        </Modal.Footer>
      </Form>
    </Modal>
  );
}
